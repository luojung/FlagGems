def select_config(a, b):
    m, k = a.shape
    n = b.shape[1]
    key = (str(a.dtype), m, n, k, *a.stride(), *b.stride())
    if key in CONFIGS:
        return CONFIGS[key]
    if k <= 16:
        return {"kind": "small", "block": 256, "warps": 4}
    if (m <= 8 or n <= 16) and k <= 2048:
        return {"kind": "reduce", "bo": 4, "warps": 4}
    return None
